uint64
sys_exit(void)
{
  int n;
  if(argint(0, &n) < 0)
    return -1;
  exit(n);
  return 0;  // not reached
}

uint64
sys_getpid(void)
{
  return myproc()->pid;
}

uint64
sys_fork(void)
{
  return fork();
}

uint64
sys_wait(void)
{
  uint64 p;
  if(argaddr(0, &p) < 0)
    return -1;
  return wait(p);
}

uint64
sys_sbrk(void)
{
  int addr;
  int n;

  if(argint(0, &n) < 0)
    return -1;
  addr = myproc()->sz;
  if(growproc(n) < 0)
    return -1;
  return addr;
}

uint64
sys_sleep(void)
{
  int n;
  uint ticks0;

  if(argint(0, &n) < 0)
    return -1;
  acquire(&tickslock);
  ticks0 = ticks;
  while(ticks - ticks0 < n){
    if(myproc()->killed){
      release(&tickslock);
      return -1;
    }
    sleep(&ticks, &tickslock);
  }
  release(&tickslock);
  return 0;
}

uint64
sys_kill(void)
{
  int pid;

  if(argint(0, &pid) < 0)
    return -1;
  return kill(pid);
}

// return how many clock tick interrupts have occurred
// since start.
uint64
sys_uptime(void)
{
  uint xticks;

  acquire(&tickslock);
  xticks = ticks;
  release(&tickslock);
  return xticks;
}

uint64 sys_trace(void){
  // 暂定思路：修改proc结构体中的某个变量，然后在syscall那里，判断如果状态为真就进行打印,如果这个变量为假就不进行多余操作
  // 由于题目要求：trace系统调用应为调用它的进程及其随后 fork 的任何子进程启用跟踪，所以fork中创建子进程时，应该复制父亲的proc变量中的掩码变量

  // 需要从用户态中获取传递给trace函数的参数
  int mask;
  if(argint(0,&mask)<0){
    // trace 返回-1即跟踪失败，就对应trace.c中的条件判断那样
    return -1;
  }
  myproc()->mask=mask;

  return 0;
} 